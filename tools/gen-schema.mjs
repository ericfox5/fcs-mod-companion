#!/usr/bin/env node
// Generate packages/ncaa14/src/schema.generated.ts from the community EA DB Editor configs
// ("Xan's NCAA 14 Dynasty/Roster Config.xml"): table names, field display names, types and enumerations.
import { readFileSync, writeFileSync } from 'node:fs';

const sources = process.argv.slice(2);
if (sources.length === 0) {
  sources.push(
    "C:/Users/efoxo/Downloads/Givee Screenshots/EA DB Editor/EA DB Editor/Xan's NCAA 14 Dynasty Config.xml",
    "C:/Users/efoxo/Downloads/Givee Screenshots/EA DB Editor/EA DB Editor/Xan's NCAA 14 Roster Config.xml",
  );
}
const unescape = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").trim();

const tables = {};
const fields = {};
for (const src of sources) {
  const xml = readFileSync(src, 'utf8');
  for (const m of xml.matchAll(/<Table>\s*<Abbreviation>([^<]*)<\/Abbreviation>\s*<Name>([^<]*)<\/Name>\s*<\/Table>/g)) {
    const abbr = m[1].trim();
    if (abbr && m[2].trim() && !tables[abbr]) tables[abbr] = unescape(m[2]);
  }
  for (const m of xml.matchAll(/<Field>\s*<Abbreviation>([^<]*)<\/Abbreviation>\s*<Name>([^<]*)<\/Name>\s*<ControlType>([^<]*)<\/ControlType>([\s\S]*?)<\/Field>/g)) {
    const abbr = m[1].trim();
    if (!abbr) continue;
    const body = m[4];
    const desc = unescape(body.match(/<Description>([^<]*)<\/Description>/)?.[1] ?? '');
    const type = (body.match(/<Type>([^<]*)<\/Type>/)?.[1] ?? '').trim();
    const items = [...body.matchAll(/<ControlItem>\(?(-?\d+)\)?\s*([^<]*)<\/ControlItem>/g)];
    const entry = fields[abbr] ?? (fields[abbr] = { name: '', control: m[3].trim(), type });
    if (!entry.name && m[2].trim()) entry.name = unescape(m[2]);
    if (desc && !entry.description) entry.description = desc;
    if (items.length && !entry.enum) entry.enum = Object.fromEntries(items.map((i) => [Number(i[1]), unescape(i[2])]));
  }
}
const out = `// GENERATED by tools/gen-schema.mjs from the EA DB Editor NCAA 14 configs. Do not edit by hand.
export interface FieldInfo { name: string; control: string; type: string; description?: string; enum?: Record<number, string> }
export const TABLE_NAMES: Record<string, string> = ${JSON.stringify(tables, null, 1)};
export const FIELD_INFO: Record<string, FieldInfo> = ${JSON.stringify(fields, null, 1)};
export function fieldName(code: string): string { return FIELD_INFO[code]?.name || code; }
export function enumLabel(code: string, value: number): string | undefined { return FIELD_INFO[code]?.enum?.[value]; }
`;
writeFileSync('packages/ncaa14/src/schema.generated.ts', out);
console.log(`tables: ${Object.keys(tables).length}, fields: ${Object.keys(fields).length}, enums: ${Object.values(fields).filter((f) => f.enum).length}`);
