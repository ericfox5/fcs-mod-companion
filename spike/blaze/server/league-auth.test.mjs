import test from 'node:test';
import assert from 'node:assert/strict';
import { MAGIC,digest,authenticate,authorizeDod,canReadContent,canReadSharedContent,validateRegistry,isPublicDynasty,mayJoinDynasty,canSeeInSearch,matchesDynastyQuery } from './league-auth.mjs';
const ta=Buffer.concat([MAGIC,Buffer.alloc(64,1)]),tb=Buffer.concat([MAGIC,Buffer.alloc(64,2)]);
const registry={version:1,players:[{userId:101,onlineId:'SameName',ticketSha256:digest(ta),joinDynasties:[]},
  {userId:202,onlineId:'SameName',ticketSha256:digest(tb),joinDynasties:[8]}]};
const a=authenticate(ta,registry),b=authenticate(tb,registry);
const store={dynasties:{8:{week:3,members:[{blazeId:101,team:1,commissioner:true},{blazeId:202,team:2,commissioner:false}]},
  9:{members:[{blazeId:303,team:3,commissioner:true}]}}};
const file=id=>({11:{cid:11,owner:101,group:{id:8}},22:{cid:22,owner:202,group:{id:8}}})[id];
test('credential proof selects numeric identity even with identical display names',()=>{
  assert.equal(a.userId,101);assert.equal(b.userId,202);
  assert.throws(()=>authenticate(Buffer.alloc(0),registry));
  assert.throws(()=>authenticate(Buffer.concat([MAGIC,Buffer.alloc(64,3)]),registry));
  assert.throws(()=>authenticate(ta,{...registry,players:registry.players.map(p=>({...p,disabled:true}))}));
  assert.throws(()=>validateRegistry({...registry,players:[...registry.players,registry.players[0]]}));
});
test('dynasty ownership and commissioner checks fail closed',()=>{
  assert(authorizeDod(88,{DYID:8},a,store,file));
  assert(!authorizeDod(88,{DYID:8},b,store,file));
  assert(authorizeDod(5,{DID:9},b,store,file));
  assert(authorizeDod(23,{DYNI:9,TABL:0x58435446},b,store,file));
  const hidden=structuredClone(store); hidden.dynasties[9].private=true;
  assert(!authorizeDod(5,{DID:9},b,hidden,file));
  assert(!authorizeDod(23,{DYNI:9,TABL:0x58435446},b,hidden,file));
  assert(!authorizeDod(12,{DYID:9,TABL:0x5445414d},b,store,file));
  assert(!authorizeDod(2,{},null,store,file));
  assert(!authorizeDod(999,{DID:8},a,store,file));
  assert(!authorizeDod(58,{DYID:8,TMID:1},b,store,file));
  assert(authorizeDod(14,{DID:8,BZID:0},b,store,file));
  assert(authorizeDod(14,{DID:8,BZID:202},b,store,file));
  assert(!authorizeDod(14,{DID:8,BZID:101},b,store,file));
  assert(authorizeDod(14,{DID:8,BZID:202},a,store,file));
  assert(authorizeDod(58,{DYID:8,TMID:2},b,store,file));
});
test('update transactions and file ownership cannot cross accounts',()=>{
  const s=structuredClone(store);s.dynasties[8].update={byUser:101,updt:0};
  assert(!authorizeDod(12,{DYID:8,TABL:0x5445414d},b,s,file));
  assert(authorizeDod(12,{DYID:8,TABL:0x5445414d},a,s,file));
  assert(!authorizeDod(12,{DYID:8,TABL:0x2e2e2f78},a,s,file));
  assert(!authorizeDod(57,{DYID:8,UPDT:0,FID:22},a,s,file));
  assert(authorizeDod(57,{DYID:8,UPDT:0,FID:11},a,s,file));
  assert(!authorizeDod(57,{DYID:8,UPDT:1,TMID:1,FID:11},b,store,file));
  assert(authorizeDod(57,{DYID:8,UPDT:1,TMID:2,FID:22},b,store,file));
  assert(authorizeDod(57,{DYID:8,UPDT:1,TMID:1023,FID:22},b,store,file));
});
test('hub reads with no dynasty id are allowed for a logged-in user',()=>{
  assert(authorizeDod(70,{},a,store,file));
  assert(authorizeDod(69,{},a,store,file));
  assert(authorizeDod(93,{},a,store,file));
  assert(!authorizeDod(93,{},null,store,file));
  assert(!authorizeDod(5,{},a,store,file));
  assert(authorizeDod(93,{DYID:9},b,store,file));
  const hiddenHub=structuredClone(store); hiddenHub.dynasties[9].private=true;
  assert(!authorizeDod(93,{DYID:9},b,hiddenHub,file));
  assert(authorizeDod(93,{DYID:8},b,store,file));
  assert(authorizeDod(67,{MAXD:5},a,store,file));
  assert(authorizeDod(67,{DYID:8,MAXD:5},a,store,file));
  assert(!authorizeDod(67,{DYID:8,MAXD:5},b,store,file));
});
test('join grants and Locker reads use numeric membership',()=>{
  const s=structuredClone(store);s.dynasties[8].members.pop();
  s.dynasties[9].private = true;
  assert(authorizeDod(6,{DID:8},b,s,file));
  assert(!authorizeDod(6,{DID:9},b,s,file));
  assert(!canReadContent(file(11),b,s.dynasties));
  assert(canReadContent(file(11),a,s.dynasties));
  assert(canReadContent(file(11),b,store.dynasties));
});
test('public dynasties are searchable and joinable',()=>{
  const coach={id:11,request:{NAME:'coach1',PASS:'',DSKL:3,OSKL:3,USKL:3,QTR:8},members:[{blazeId:1,team:18,commissioner:true}]};
  const hidden={id:10,private:true,request:{NAME:'hidden',PASS:'secret'},members:[{blazeId:303,commissioner:true}]};
  const mine={id:12,private:true,request:{NAME:'mine',PASS:''},members:[{blazeId:202,commissioner:true}]};
  const locked={id:13,request:{NAME:'locked',PASS:'secret',PRIV:0},members:[{blazeId:303,commissioner:true}]};
  const s={dynasties:{11:coach,10:hidden,12:mine,13:locked}};
  assert(isPublicDynasty(coach));
  assert(!isPublicDynasty(hidden));
  assert(!isPublicDynasty({request:{PRIV:1},members:[]}));
  assert(!isPublicDynasty({vis:0,request:{},members:[]}));
  assert(mayJoinDynasty(coach,b,{}));
  assert(mayJoinDynasty(coach,{userId:700001,leagueAuthenticated:true,joinDynasties:[]},{}));
  assert(!mayJoinDynasty(hidden,b,{PASS:'secret'}));
  assert(!mayJoinDynasty(locked,b,{PASS:'nope'}));
  assert(mayJoinDynasty(locked,b,{PASS:'secret'}));
  assert(mayJoinDynasty(mine,b,{}));
  const granted={id:8,private:true,request:{NAME:'grant',PASS:''},members:[{blazeId:101,commissioner:true}]};
  assert(mayJoinDynasty(granted,b,{}));
  assert(!mayJoinDynasty(granted,{userId:404,leagueAuthenticated:true,joinDynasties:[]},{}));
  assert(authorizeDod(6,{DID:11},b,s,file));
  assert(!authorizeDod(6,{DID:10,PASS:'secret'},b,s,file));
  assert(!authorizeDod(6,{DID:13,PASS:'nope'},b,s,file));
  assert(authorizeDod(6,{DID:13,PASS:'secret'},b,s,file));
  const open={NAME:'',PRIV:0x7fffffff,TEAM:1023,DSKL:0x7fffffff,OSKL:0x7fffffff,USKL:0x7fffffff,QTR:0x7fffffff,MAXR:100};
  const visible=Object.values(s.dynasties).filter(d=>canSeeInSearch(d,b,b.userId)&&matchesDynastyQuery(d,open)).map(d=>d.id).sort((x,y)=>x-y);
  assert.deepEqual(visible,[11,12,13]);
  assert(!canSeeInSearch(hidden,b,b.userId));
  assert(canSeeInSearch(coach,null,0));
  assert(!canSeeInSearch(hidden,null,0));
  assert(matchesDynastyQuery(coach,{...open,NAME:'Coach'}));
  assert(!matchesDynastyQuery(coach,{...open,NAME:'efox'}));
  assert(matchesDynastyQuery(coach,{...open,TEAM:18}));
  assert(!matchesDynastyQuery(coach,{...open,TEAM:40}));
  assert(!matchesDynastyQuery(coach,{...open,DSKL:1}));
  assert(matchesDynastyQuery(coach,{...open,QTR:8}));
  assert(!matchesDynastyQuery(coach,{...open,PRIV:1}));
  assert(matchesDynastyQuery(coach,{...open,PRIV:0}));
  assert(!matchesDynastyQuery(hidden,{...open,PRIV:0}));
  assert(matchesDynastyQuery(hidden,{...open,PRIV:1}));
  const pubFile={cid:297,owner:1,group:{id:11}}, privFile={cid:10,owner:303,group:{id:10}};
  assert(canReadSharedContent(pubFile,b,s.dynasties));
  assert(!canReadContent(pubFile,b,s.dynasties));
  assert(!canReadSharedContent(privFile,b,s.dynasties));
});
